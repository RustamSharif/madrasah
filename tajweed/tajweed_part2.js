// Автоматическая синхронизация ключей глав 4, 5 и 6 с кнопками в index.html
document.addEventListener("DOMContentLoaded", () => {
  const btns = Array.from(document.querySelectorAll("button[onclick*='startQuiz']"));
  const mapKeys = [
    { idx: 3, defaultKey: "Сыфаты" },
    { idx: 4, defaultKey: "Нун сакина" },
    { idx: 5, defaultKey: "Мим сакина" }
  ];
  mapKeys.forEach(({ idx, defaultKey }) => {
    if (btns[idx]) {
      const m = btns[idx].getAttribute("onclick").match(/startQuiz\(['"]([^'"]+)['"]\)/);
      if (m && m[1] && m[1] !== defaultKey) {
        const realKey = m[1];
        if (window.TAJWEED_DATA.cheatsheets[defaultKey]) {
          window.TAJWEED_DATA.cheatsheets[realKey] = window.TAJWEED_DATA.cheatsheets[defaultKey];
        }
        window.TAJWEED_DATA.questions.forEach(q => {
          if (q.chapter === defaultKey) q.chapter = realKey;
        });
      }
    }
  });
});
