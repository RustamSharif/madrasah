        const rawText = btns[btnIdx].innerText.replace(/^\d+\.\s*/, "").split("\n")[0].trim();
        const attrMatch = (btns[btnIdx].getAttribute("onclick") || "").match(/['"]([^'"]+)['"]/);
        const targetKey = attrMatch ? attrMatch[1] : rawText;
        if (targetKey && targetKey !== keys[i] && !window.ADAB_DATA.cheatsheets[targetKey]) {
          window.ADAB_DATA.cheatsheets[targetKey] = partCheats[keys[i]];
          partQuestions.forEach(q => {
            if (q.chapter === keys[i]) q.chapter = targetKey;
          });
        }
